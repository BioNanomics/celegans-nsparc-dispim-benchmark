"""One-page, human-readable summary of a report (summary.md).

Only re-presents numbers already computed by metrics.summarize(); it adds no new metric.
"""

from __future__ import annotations

import csv
from pathlib import Path
from typing import Any

from . import __version__
from .metrics import Gates

_STATUS = {"pass": "PASS", "fail": "FAIL", "not_evaluable": "NOT EVALUABLE"}
_FABRICATED = "FABRICATED example data: numbers are for software testing only"


def fmt_rate(num: int, den: int) -> str:
    """'91.7% (11/12)'; no denominator is 'n/a' (unknown), never 0."""
    return f"{100 * num / den:.1f}% ({num}/{den})" if den else "n/a"


def auto_label(data_dir: str | Path, label: str | None) -> str | None:
    """An explicit label wins; otherwise label the report FABRICATED when the data says so.

    Fabricated example data carries 'FABRICATED' in acquisitions.csv notes. The folder name
    is deliberately ignored: real data may sit under a path containing 'synthetic'.
    """
    if label and label.strip():
        return label.strip()
    path = Path(data_dir) / "acquisitions.csv"
    try:
        with path.open(encoding="utf-8-sig", newline="") as handle:
            if any("FABRICATED" in (row.get("notes") or "").upper() for row in csv.DictReader(handle)):
                return _FABRICATED
    except OSError:
        pass
    return None


def _cell(value: Any) -> str:
    return str(value).replace("|", "\\|")


def _table(headers: list[str], rows: list[list[Any]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    lines += ["| " + " | ".join(_cell(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def _section(title: str, body: str) -> str:
    return f"## {title}\n\n{body}\n"


def _hatching(g: dict[str, Any]) -> str:
    known, unknown = g["hatching_known_n"], g["hatching_unknown_n"]
    if known:
        return f"{g['hatching_n']}/{known} known, {unknown} unknown"
    return f"n/a ({known} known, {unknown} unknown)"


def _detection(r: dict[str, Any]) -> str:
    return fmt_rate(r["tp"], r["tp"] + r["fn"])


def _precision(r: dict[str, Any]) -> str:
    return fmt_rate(r["tp"], r["tp"] + r["fp"])


def render_summary(report: dict[str, list[dict[str, Any]]], gates: Gates,
                   warnings: list[str], label: str | None = None) -> str:
    banner = f"> **DATA LABEL: {label}**\n\n" if label else ""
    parts = [f"# Report summary\n\n{banner}Generated by celegans-benchmark v{__version__}.\n"]

    groups = report["groups"]
    if not report["embryos"] and all(g["n_attempted"] == 0 for g in groups):
        parts.append("No embryos registered; there is nothing to summarize yet.\n")

    parts.append(_section("Groups", _table(
        ["Group", "Attempted", "Included", "Excluded", "Hatching", "Audited volumes",
         "Detection recall", "Precision", "Lineage links correct"],
        [[g["group"], g["n_attempted"], g["n_included"], g["n_excluded"], _hatching(g),
          g["audited_volumes"], _detection(g), _precision(g),
          fmt_rate(g["correct_lineage_events"], g["verified_lineage_events"])]
         for g in groups])))

    gate_names = {"detection_recall": f"Detection recall (frames with ≤ {gates.recall_through_cells} cells)",
                  "lineage_correct": "Verified lineage links correct"}
    parts.append(_section("Feasibility gates", _table(
        ["Group", "Gate", "Result", "Target", "Embryos", "Status"],
        [[g["group"], gate_names[g["gate"]], fmt_rate(g["numerator"], g["denominator"]),
          f"≥ {100 * g['threshold']:g}%", g["n_embryos"], _STATUS[g["status"]]]
         for g in report["feasibility_gates"]])
        + "\n\nTargets are provisional internal goals, not diSPIM standards. "
          "NOT EVALUABLE means there is no data to judge; it is never counted as a failure."))

    stage = report["stage_qc"]
    parts.append(_section("Detection by stage", _table(
        ["Group", "Stage (nuclei)", "Audited volumes", "Recall", "Precision"],
        [[r["group"], r["stage"], r["audited_volumes"], _detection(r), _precision(r)]
         for r in stage]) if stage else "No audited frames."))

    lineage = report["lineage_stage_qc"]
    parts.append(_section("Lineage links by stage", _table(
        ["Group", "Stage (nuclei)", "Verified links", "Correct"],
        [[r["group"], r["stage"], r["verified_lineage_events"],
          fmt_rate(r["correct_lineage_events"], r["verified_lineage_events"])]
         for r in lineage]) if lineage else "No verified lineage links."))

    depth = report["depth_qc"]
    if any(r["depth_region"] != "all" for r in depth):
        parts.append(_section("Depth (near/far)", _table(
            ["Group", "Region", "Stage (nuclei)", "Audited rows", "Recall", "Precision"],
            [[r["group"], r["depth_region"], r["stage"], r["audited_volumes"],
              _detection(r), _precision(r)] for r in depth])))

    embryos = report["embryos"]
    hatched = {1: "yes", 0: "no", None: "unknown"}
    parts.append(_section("Embryos", _table(
        ["Embryo", "Group", "Hatched", "Audited volumes", "Detection recall", "Lineage links correct"],
        [[e["embryo_id"], e["group"], hatched[e["hatched"]], e["n_audited_volumes"],
          _detection(e), fmt_rate(e["correct_lineage_events"], e["verified_lineage_events"])]
         for e in embryos]) if embryos else "No included embryos."))

    parts.append(_section("Warnings", "\n".join(f"- {w}" for w in warnings) if warnings
                          else "No warnings."))

    parts.append("---\n\nThese figures are descriptive. The embryo is the independent unit; rates "
                 "pooled over frames or nuclei are technical descriptors, not independent replicates. "
                 "This is not an equivalence or safety test. A blank or n/a means not measured or "
                 "undefined, never zero.\n")
    return "\n".join(parts)


def write_summary(text: str, output_dir: str | Path) -> Path:
    directory = Path(output_dir)
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / "summary.md"
    path.write_text(text, encoding="utf-8", newline="\n")
    return path
